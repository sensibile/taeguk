#!/usr/bin/env python3
"""Find mechanical drift in documents outside docs/rules; findings are candidates, not failures."""
import argparse
import json
from pathlib import Path
import re
import sys
import tomllib
from urllib.parse import unquote, urlsplit

# python3 -I drops the script directory from sys.path; check_rules sits next to this file.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_rules import anchors  # noqa: E402

# docs/rules is covered by check_rules.py; the research archive is a frozen record.
SKIP = ('docs/rules/', 'docs/research/archive/')
SKIP_PARTS = {'.git', '.taeguk', '_build', 'deps', 'target', 'node_modules', 'cover'}
# Generated by the installer into each project, so it has no source directory here.
GENERATED_SKILLS = {'taeguk-init'}
REPO_DIRS = ('docs/', 'scripts/', 'codex/', 'apps/', 'tools/', 'installer/', 'tests/', '.github/')


def documents(root):
    for path in sorted(root.rglob('*.md')):
        rel = path.relative_to(root).as_posix()
        if SKIP_PARTS & set(path.relative_to(root).parts) or rel.startswith(SKIP):
            continue
        yield path, rel


def scan(root):
    root = Path(root).resolve()
    registry = tomllib.loads((root/'docs/rules/registry.toml').read_text(encoding='utf-8'))
    versions = {rule['id']: rule['version'] for rule in registry['rules']}
    skills = {p.name for p in (root/'codex/skills').iterdir() if (p/'SKILL.md').is_file()} | GENERATED_SKILLS
    findings = []
    for path, rel in documents(root):
        text = path.read_text(encoding='utf-8')
        for number, line in enumerate(text.splitlines(), 1):
            def add(kind, value, detail):
                findings.append({'kind': kind, 'file': rel, 'line': number, 'value': value, 'detail': detail})
            # Inline links with an optional title, and reference definitions ([ref]: target).
            links = re.findall(r'\]\(<?([^)\s>]+)>?(?:\s+"[^"]*")?\)', line)
            links += re.findall(r'^\s{0,3}\[[^\]]+\]:\s*<?([^\s>]+)>?', line)
            for value in links:
                parts = urlsplit(value)
                if parts.scheme or parts.netloc:
                    continue
                target = path.parent/unquote(parts.path) if parts.path else path
                if not target.exists():
                    add('link', value, 'local link target does not exist')
                elif parts.fragment and target.suffix == '.md' and unquote(parts.fragment) not in anchors(
                        text if target == path else target.read_text(encoding='utf-8')):
                    add('link', value, 'heading anchor does not exist in the target')
            for name in re.findall(r'\$(taeguk-[a-z0-9-]*[a-z0-9])', line):
                if name not in skills:
                    add('skill', name, 'no codex/skills directory with this name')
            # No trailing \b: a Korean particle right after the version (1.2와) is a word character.
            for ident, version in re.findall(r'(?<![A-Za-z0-9])([A-Z]{3}-[0-9]{3}) ([0-9]+\.[0-9]+)(?!\.?[0-9])', line):
                if ident in versions and versions[ident] != version:
                    add('rule_version', f'{ident} {version}', f'registry has {versions[ident]}; check whether the citation is historical')
            for value in re.findall(r'`([^`\s<>*{}$]+)`', line):
                if value.startswith(REPO_DIRS) and not (root/value.rstrip('/')).exists():
                    add('path', value, 'repository path in a code span does not exist')
    return findings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    findings = scan(parser.parse_args().root)
    print(json.dumps({'status': 'FINDINGS' if findings else 'NONE', 'scope': 'mechanical_document_drift_only',
                      'findings': findings, 'limits': ['no semantic comparison', 'docs/rules is checked by check_rules.py',
                                                       'a finding is a candidate, not a defect']}, ensure_ascii=False, indent=2))
    return bool(findings)


if __name__ == '__main__':
    raise SystemExit(main())
